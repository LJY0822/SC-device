const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');
let callback=null;
const context=vm.createContext({console:{log(){}},document:{getElementById(){return null;},querySelector(){return null;}},window:{setTimeout(fn){callback=fn;return 1;},clearTimeout(){callback=null;}}});
vm.runInContext(fs.readFileSync('scripts/chat.js','utf8'),context);
const run=code=>vm.runInContext(code,context);
run('Chat.currentSession={mode:0};Chat._setQuote({text:"online quote"})');
assert.equal(run('Chat._currentQuote.text'),'online quote');
run('Chat._syncModeToggleLabel=()=>{};Chat._updateTypingDisplay=()=>{};Chat._applyModeUI(1)');
assert.equal(run('Chat._currentQuote'),null,'entering offline mode clears a pending online quote');
run('Chat.currentSession.mode=1;Chat._setQuote({text:"hidden quote"})');
assert.equal(run('Chat._currentQuote'),null,'offline quoting is rejected at the shared entry point');
const listeners={};context.target={addEventListener(name,fn){listeners[name]=fn;}};
run('Chat._attachMessageLongPress(target,{text:"long press"})');
listeners.touchstart();assert.equal(callback,null,'offline touch must not start quoting');
listeners.mousedown({button:0});assert.equal(callback,null,'offline mouse must not start quoting');
run('Chat.currentSession.mode=0');listeners.touchstart();assert.equal(typeof callback,'function');
callback();assert.equal(run('Chat._currentQuote.text'),'long press','online long press still quotes');
listeners.touchstart();run('Chat.currentSession.mode=1');callback();
assert.equal(run('Chat._currentQuote'),null,'mode changes during a held press cannot create hidden quotes');
console.log('PASS chat quote: online touch, offline touch/mouse, pending quote cleanup and mode-switch race');
